int isExecutable(char *input, char *tempPath, char *candidatePath,
                 char *candidate) {
  char *myPath = strtok(tempPath, ":");
  while (myPath != NULL) {
    strcpy(candidatePath, myPath);
    strcat(candidatePath, "/");
    strcat(candidatePath, candidate);
    // printf("Checking: %s\n", candidatePath);
    if (access(candidatePath, X_OK) == 0) {
      return 1;
    }
    myPath = strtok(NULL, ":");
  }
  return 0;
}

